/* Uses only the disposable saldo-smoke-* project; never a personal database. */
const assert = require('node:assert/strict');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
if (!process.env.COMPOSE_PROJECT_NAME?.startsWith('saldo-smoke-') || !process.env.SALDO_QA_TOOLS || !process.env.SALDO_UI_URL) throw new Error('Configure projeto saldo-smoke-*, SALDO_QA_TOOLS e SALDO_UI_URL');
const { chromium } = require(path.join(process.env.SALDO_QA_TOOLS, 'node_modules/playwright'));
const { default: AxeBuilder } = require(path.join(process.env.SALDO_QA_TOOLS, 'node_modules/@axe-core/playwright'));
const origin = process.env.SALDO_UI_URL;
const dockerExecutable = process.env.DOCKER_EXECUTABLE ?? '/usr/bin/docker';
if (!path.isAbsolute(dockerExecutable)) throw new Error('DOCKER_EXECUTABLE must be an absolute path');
async function accessibility(page, label) {
  const results = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
  assert.deepEqual(results.violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) })), [], label);
}
(async () => {
  execFileSync(dockerExecutable, ['compose', 'exec', '-T', 'db', 'psql', '-U', 'contasedia', '-d', 'contasedia', '-c',
    "INSERT INTO taxas_referencia (chave,taxa_anual,fonte,consultada_em) VALUES ('SELIC',15,'Taxa fictícia QA',NOW()) ON CONFLICT (chave) DO UPDATE SET taxa_anual=15,fonte='Taxa fictícia QA',consultada_em=NOW();"], { stdio: 'pipe' });
  const browser = await chromium.launch({ executablePath: process.env.SALDO_CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'pt-BR', timezoneId: 'America/Sao_Paulo', reducedMotion: 'reduce' });
    const page = await context.newPage();
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const email = `charges.${crypto.randomUUID()}@example.org`, senha = crypto.randomBytes(20).toString('hex');
    await page.goto(`${origin}/cadastro`);
    await page.getByLabel('Nome', { exact: true }).fill('Validação Encargos');
    await page.getByLabel('E-mail', { exact: true }).fill(email);
    await page.getByLabel('Senha', { exact: true }).fill(senha);
    await page.getByLabel('Confirmar senha', { exact: true }).fill('divergente');
    await page.getByRole('button', { name: 'Criar conta', exact: true }).click();
    await page.getByText('As senhas devem ser iguais', { exact: true }).waitFor();
    assert.equal(await page.locator('#register-senha').getAttribute('aria-invalid'), 'false');
    await accessibility(page, 'cadastro com confirmação inválida');
    await page.getByLabel('Confirmar senha', { exact: true }).fill(senha);
    await page.getByRole('button', { name: 'Criar conta', exact: true }).click();
    await page.getByText('Cadastro realizado!', { exact: true }).waitFor();
    await page.getByRole('link', { name: 'Ir para o login', exact: true }).click();
    assert.equal(await page.getByLabel('E-mail', { exact: true }).inputValue(), email);
    await page.getByLabel('Senha', { exact: true }).fill(senha);
    await page.getByRole('button', { name: 'Entrar', exact: true }).click();
    const navigate = name => page.getByRole('navigation').getByRole('link', { name, exact: true }).click();
    await navigate('Configurações');
    await page.getByLabel('Tipo padrão para novas contas', { exact: false }).selectOption('RECORRENTE');
    await page.getByRole('checkbox', { name: /Revisar antes/ }).uncheck();
    await page.getByRole('checkbox', { name: /Reduzir animações/ }).check();
    await page.getByRole('button', { name: 'Salvar configurações', exact: true }).click();
    await page.getByText('Configurações salvas. As preferências já estão em uso.', { exact: true }).waitFor();
    await page.reload();
    await page.getByText('Suas preferências estão atualizadas.', { exact: true }).waitFor();
    assert.equal(await page.getByLabel('Tipo padrão para novas contas', { exact: false }).inputValue(), 'RECORRENTE');
    await accessibility(page, 'configurações desktop');
    await page.screenshot({ path: path.join(process.env.SALDO_QA_TOOLS, 'configuracoes-atualizadas.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await accessibility(page, 'configurações mobile');
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.setViewportSize({ width: 1440, height: 1000 });
    await navigate('Contas');
    await page.getByRole('button', { name: 'Nova conta', exact: true }).click();
    const dialog = page.getByRole('dialog');
    assert.equal(await dialog.getByLabel('Tipo', { exact: true }).inputValue(), 'RECORRENTE');
    await dialog.getByRole('button', { name: 'Cancelar', exact: true }).click();
    const session = await page.evaluate(() => JSON.parse(localStorage.getItem('contasemdia:session')));
    const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Sao_Paulo' }).format(new Date());
    const due = new Date(`${today}T00:00:00Z`); due.setUTCDate(due.getUTCDate() - 30);
    const created = await fetch(`${origin}/api/accounts`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${session.token}` }, body: JSON.stringify({ descricao: 'Encargos automáticos QA', valor: 60, vencimento: due.toISOString().slice(0, 10), tipo: 'AVULSA', recorrencia: null }) });
    assert.equal(created.status, 201);
    const { account } = await created.json();
    await page.reload();
    await page.getByRole('button', { name: 'Pagar Encargos automáticos QA', exact: true }).click();
    await dialog.getByRole('checkbox', { name: /Também paguei encargos/ }).check();
    await dialog.getByText('Encargos calculados', { exact: true }).waitFor();
    assert.equal(await dialog.locator('[name=encargos]').count(), 0);
    assert.match(await dialog.locator('.payment-total-preview').textContent(), /60,74/);
    await dialog.getByLabel('Valor do pagamento', { exact: true }).fill('30');
    await page.waitForResponse(response => response.url().endsWith('/payments/preview') && response.status() === 200);
    await page.waitForFunction(() => document.querySelector('.payment-total-preview')?.textContent.includes('30,37'));
    await accessibility(page, 'encargos automáticos desktop');
    await page.screenshot({ path: path.join(process.env.SALDO_QA_TOOLS, 'encargos-automaticos.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await accessibility(page, 'encargos automáticos mobile');
    await dialog.getByRole('button', { name: 'Registrar pagamento', exact: true }).click();
    await dialog.getByRole('heading', { name: 'Revisar pagamento', exact: true }).waitFor();
    await dialog.getByRole('button', { name: 'Confirmar pagamento', exact: true }).click();
    await dialog.getByRole('heading', { name: 'Pagamento registrado', exact: true }).waitFor();
    assert.match(await dialog.locator('.receipt-total').textContent(), /30,37/);
    const payments = await (await fetch(`${origin}/api/payments?contaId=${encodeURIComponent(account.id)}`, { headers: { Authorization: `Bearer ${session.token}` } })).json();
    assert.equal(payments.payments.length, 1); assert.equal(Number(payments.payments[0].valor), 30); assert.equal(Number(payments.payments[0].encargos), .37);
    const fresh = await (await fetch(`${origin}/api/accounts/${encodeURIComponent(account.id)}`, { headers: { Authorization: `Bearer ${session.token}` } })).json();
    assert.equal(fresh.account.saldo, 30);
    assert.deepEqual(errors, []);
    console.log('PASS Chrome: cadastro → login preenchido → preferências persistidas → encargos automáticos parciais → confirmação → histórico e saldo');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
